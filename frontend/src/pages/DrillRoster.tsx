import { useEffect, useState } from 'react';
import { attendanceApi, type AttendanceToday } from '@/api/attendance';

// REQ-016: on-iPad Drill-Ready Roster. Large type, glanceable from 2ft
// during an evacuation. The PDF version (one-tap-print) lives at
// /api/drill-roster.pdf.

export default function DrillRoster(): JSX.Element {
  const [data, setData] = useState<AttendanceToday | null>(null);
  const [err, setErr] = useState<string>('');

  useEffect(() => {
    let alive = true;
    const tick = async () => {
      try {
        const d = await attendanceApi.today();
        if (alive) setData(d);
      } catch (e) {
        if (alive) setErr(e instanceof Error ? e.message : 'Failed to load');
      }
    };
    void tick();
    const t = setInterval(tick, 30000);
    return () => { alive = false; clearInterval(t); };
  }, []);

  if (err) return <div className="p-12 text-2xl text-coral-700">{err}</div>;
  if (!data) return <div className="p-12 text-2xl text-ink-400">Loading roster…</div>;

  return (
    <div className="min-h-screen bg-white p-8">
      <div className="max-w-5xl mx-auto">
        <div className="flex items-baseline justify-between mb-6">
          <h1 className="text-4xl" style={{ fontFamily: 'Fraunces, Georgia, serif' }}>Drill-Ready Roster</h1>
          <a href={attendanceApi.drillRosterURL()} target="_blank" rel="noreferrer"
            className="px-4 py-2 bg-amber-100 hover:bg-amber-200 text-amber-900 rounded-lg text-base font-medium">
            Print this page
          </a>
        </div>
        <div className="text-base text-ink-700 mb-6">As of {new Date(data.as_of).toLocaleString()}</div>

        <h2 className="text-2xl font-semibold mt-6 mb-3">Children present ({data.children_present.length})</h2>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-2">
          {data.children_present.map((c) => (
            <div key={c.id} className="border border-line rounded-lg p-3">
              <div className="text-xl font-medium">{c.first_name} {c.last_name}</div>
              <div className="text-base text-ink-700">{c.parent_name} · <a href={`tel:${c.parent_phone}`} className="underline">{c.parent_phone}</a></div>
              {c.allergies && (
                <div className="text-base mt-1 text-orange-700 font-medium">ALLERGIES: {c.allergies}</div>
              )}
            </div>
          ))}
        </div>

        <h2 className="text-2xl font-semibold mt-8 mb-3">Staff present ({data.staff_present.length})</h2>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-2">
          {data.staff_present.map((s) => (
            <div key={s.id} className="border border-line rounded-lg p-3">
              <div className="text-xl font-medium">{s.first_name} {s.last_name}</div>
              <div className="text-base text-ink-700">{s.role}</div>
            </div>
          ))}
        </div>

        <div className="mt-12 text-sm text-ink-400">Generated by Levelbrook · Refreshes every 30 seconds.</div>
      </div>
    </div>
  );
}
